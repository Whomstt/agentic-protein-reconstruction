"""CSV and LaTeX exports for the evaluation reports.

Every table the report prints is also written here as a booktabs ``.tex`` file
that can be ``\\input{}`` directly into the dissertation, so no number is ever
retyped by hand. Markdown and LaTeX are rendered from the SAME row data
(``Table``), which is what keeps them from drifting apart.

stdlib only — ``csv`` from the standard library, no pandas.
"""

from __future__ import annotations

import csv
import math
from dataclasses import dataclass, field
from pathlib import Path

# LaTeX special characters that must be escaped in any cell we emit.
_LATEX_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}

# Unicode that shows up in labels but has no place in a .tex file.
_UNICODE_TO_LATEX = {
    "Δ": r"$\Delta$",
    "−": "-",
    "±": r"$\pm$",
    "τ": r"$\tau$",
    "≈": r"$\approx$",
    "≤": r"$\leq$",
    "≥": r"$\geq$",
    "—": "---",
    "–": "--",
    "×": r"$\times$",
    "'": "'",
}


def latex_escape(text: str) -> str:
    out = []
    for char in str(text):
        if char in _UNICODE_TO_LATEX:
            out.append(_UNICODE_TO_LATEX[char])
        elif char in _LATEX_ESCAPES:
            out.append(_LATEX_ESCAPES[char])
        else:
            out.append(char)
    return "".join(out)


def fmt(value, places: int = 4, signed: bool = False, dash: str = "n/a") -> str:
    """Format a number for a table cell. None/NaN render as ``dash`` rather than
    as 0 or 'nan', so a missing measurement is visibly missing."""
    if value is None:
        return dash
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (int, float)):
        if isinstance(value, float) and (math.isnan(value) or math.isinf(value)):
            return dash
        if isinstance(value, int):
            return f"{value:+d}" if signed else f"{value:d}"
        return f"{value:+.{places}f}" if signed else f"{value:.{places}f}"
    return str(value)


def fmt_ci(interval, places: int = 4, dash: str = "n/a") -> str:
    """Render an Interval (or dict form) as 'point [low, high]'."""
    if interval is None:
        return dash
    data = interval if isinstance(interval, dict) else interval.as_dict()
    point, low, high = data.get("point"), data.get("low"), data.get("high")
    if point is None or (isinstance(point, float) and math.isnan(point)):
        return dash
    if low is None or (isinstance(low, float) and math.isnan(low)):
        return fmt(point, places)
    return f"{fmt(point, places)} [{fmt(low, places)}, {fmt(high, places)}]"


def fmt_p(value, dash: str = "n/a") -> str:
    """P-values: small ones as '<0.001' rather than a run of zeros."""
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return dash
    if value < 0.001:
        return "<0.001"
    return f"{value:.3f}"


@dataclass
class Table:
    """One table, rendered to both markdown and booktabs LaTeX from one source.

    ``key`` names the .tex file. ``caption``/``label`` are LaTeX-only.
    """

    key: str
    headers: list[str]
    rows: list[list]
    caption: str = ""
    label: str = ""
    notes: str = ""
    column_spec: str = ""
    formatted: bool = True
    _extra: dict = field(default_factory=dict)

    @staticmethod
    def _md_cell(value) -> str:
        """A literal pipe inside a cell would end the column early and silently
        corrupt the rendered table, so escape it."""
        if value is None:
            return ""
        return str(value).replace("|", r"\|")

    def to_markdown(self) -> str:
        header = "| " + " | ".join(self._md_cell(h) for h in self.headers) + " |"
        divider = "| " + " | ".join("---" for _ in self.headers) + " |"
        body = [
            "| " + " | ".join(self._md_cell(c) for c in row) + " |" for row in self.rows
        ]
        return "\n".join([header, divider, *body])

    def to_latex(self) -> str:
        spec = self.column_spec or ("l" + "r" * (len(self.headers) - 1))
        lines = [
            "% Generated by evaluation/exports.py - do not edit by hand.",
            "% Regenerate with: python -m evaluation.rebuild --all",
            r"\begin{table}[htbp]",
            r"  \centering",
        ]
        if self.caption:
            lines.append(rf"  \caption{{{latex_escape(self.caption)}}}")
        if self.label:
            lines.append(rf"  \label{{{self.label}}}")
        lines += [
            rf"  \begin{{tabular}}{{{spec}}}",
            r"    \toprule",
            "    " + " & ".join(latex_escape(h) for h in self.headers) + r" \\",
            r"    \midrule",
        ]
        for row in self.rows:
            cells = ["" if c is None else latex_escape(c) for c in row]
            lines.append("    " + " & ".join(cells) + r" \\")
        lines += [r"    \bottomrule", r"  \end{tabular}"]
        if self.notes:
            lines.append(
                rf"  \par\smallskip\footnotesize{{{latex_escape(self.notes)}}}"
            )
        lines += [r"\end{table}", ""]
        return "\n".join(lines)


def write_tables_tex(tables: list[Table], out_dir: Path) -> list[Path]:
    """One .tex file per table, plus an ``all_tables.tex`` that inputs them in
    order for convenience."""
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for table in tables:
        path = out_dir / f"{table.key}.tex"
        path.write_text(table.to_latex(), encoding="utf-8")
        written.append(path)
    index = out_dir / "all_tables.tex"
    index.write_text(
        "% Generated by evaluation/exports.py - do not edit by hand.\n"
        + "\n".join(rf"\input{{{p.stem}}}" for p in written)
        + "\n",
        encoding="utf-8",
    )
    return written


